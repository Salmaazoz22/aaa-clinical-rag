class AnswerRequest(BaseModel):
    """Body for POST /v1/answer."""

    question: str = Field(
        ...,
        description="The clinical guideline question to answer.",
        min_length=1,
        examples=["What diameter threshold triggers elective AAA repair?"],
    )
    top_k: int | None = Field(
        None,
        ge=1,
        description="Number of chunks to retrieve from the vector store. "
                    "Defaults to the value configured in generation settings.",
    )
    threshold: float | None = Field(
        None,
        ge=0.0,
        le=1.0,
        description="Minimum similarity score for a chunk to be used as evidence. "
                    "Defaults to the configured score threshold (0.75).",
    )


