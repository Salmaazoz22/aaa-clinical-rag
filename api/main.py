#: Frozen artifacts served read-only to the UI. Nothing here is recomputed:
#: the files are the ones the published evaluation was written from, and each
#: response carries the SHA-256 of the bytes that were actually read, so a
#: client can prove it is looking at the frozen record and not a live rerun.
_FROZEN_ARTIFACTS: dict[str, Path] = {
    "evaluation_results": ROOT / "eval" / "final_evaluation_results.json",
    "evaluation_summary": ROOT / "eval" / "final_evaluation_summary.json",
    "index_meta": ROOT / "data" / "embeddings" / "index_meta.json",
    "document_metadata": ROOT / "data" / "processed" / "document_metadata.json",
    "integrity_report": ROOT / "eval" / "integrity_report.json",
}


@lru_cache(maxsize=None)
def _read_frozen(name: str) -> tuple[Any, str]:
    """Read one frozen artifact and return `(parsed, sha256_of_bytes)`.

    Cached because these files never change while the service is running --
    they are build-time artifacts, not state. The digest is of the raw bytes,
    so it is comparable with `eval/final_artifact_hashes.json`.
    """
    path = _FROZEN_ARTIFACTS[name]
    raw = path.read_bytes()
    return json.loads(raw.decode("utf-8")), hashlib.sha256(raw).hexdigest()


def _frozen_or_503(name: str) -> tuple[Any, str]:
    try:
        return _read_frozen(name)
    except FileNotFoundError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Frozen artifact '{name}' is not present in this deployment.",
        ) from exc
    except (json.JSONDecodeError, OSError) as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Frozen artifact '{name}' could not be read: {exc}",
        ) from exc


def _require_retriever() -> QdrantRetriever:
    if _retriever is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "Retriever not initialised. Qdrant may be unavailable or the "
                "embedding model failed to load at startup."
            ),
        )
    return _retriever


