@app.get(
    "/health",
    summary="Health check",
    description="Returns API status, Qdrant connectivity, and index readiness.",
    tags=["ops"],
)
def health_check() -> dict[str, Any]:
    qdrant_ok = False
    index_ok = False
    points: int | None = None

    if _retriever is not None:
        try:
            col_info = _retriever.client.get_collection(_retriever.settings.collection)
            qdrant_ok = True
            index_ok = col_info.status.name == "GREEN"
            points = col_info.points_count
        except Exception:  # noqa: BLE001
            pass

    # Whether an LLM key is configured is reported here so a client can say
    # "live generation is unavailable" BEFORE a question is asked, instead of
    # discovering it from a 503 on /v1/answer. Only the boolean is exposed --
    # never the key, and never any part of it.
    try:
        gen = load_generation_settings()
        llm = {
            "configured": bool(gen.api_key),
            "provider": gen.provider,
            "model": gen.model,
        }
    except Exception as exc:  # noqa: BLE001 - a bad provider name must not 500 /health
        llm = {"configured": False, "provider": None, "model": None, "error": str(exc)}

    return {
        "status": "ok" if (qdrant_ok and index_ok) else "degraded",
        "qdrant": qdrant_ok,
        "index": index_ok,
        "points": points,
        "retriever": _retriever is not None,
        "llm": llm,
    }


@app.get(
    "/v1/meta",
    summary="Index and model metadata",
    description="Exposes the pinned model/revision, collection name, dimensions, and chunk count.",
    tags=["meta"],
)
def get_meta() -> dict[str, Any]:
    retriever = _require_retriever()

    try:
        col_info = retriever.client.get_collection(retriever.settings.collection)
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Qdrant unavailable: {exc}",
        ) from exc

    # Build-time provenance, read from the index's own manifest. Served so a
    # client can display which chunk set the running collection was built from
    # without trusting anything the UI hardcodes.
    try:
        index_meta, index_meta_sha = _read_frozen("index_meta")
    except Exception:  # noqa: BLE001 - provenance is additive; meta must still answer
        index_meta, index_meta_sha = {}, None

    gen = None
    try:
        settings = load_generation_settings()
        gen = {
            "provider": settings.provider,
            "model": settings.model,
            "api_key_supplied": bool(settings.api_key),
            "top_k": settings.top_k,
            "score_threshold": settings.score_threshold,
            "temperature": settings.temperature,
        }
    except Exception:  # noqa: BLE001
        gen = None

    return {
        "model": EXPECTED_MODEL,
        "revision": EXPECTED_REVISION,
        "dimensions": EXPECTED_DIM,
        "collection": retriever.settings.collection,
        "chunk_count": col_info.points_count,
        "index_status": col_info.status.name,
        "distance": COLLECTION_DISTANCE,
        "vector_store": "Qdrant",
        "connection": retriever.settings.describe(),
        "index_provenance": {
            "source_chunks_file": index_meta.get("source_chunks_file"),
            "source_chunks_sha256": index_meta.get("source_chunks_sha256"),
            "indexed_chunk_ids_sha256": index_meta.get("indexed_chunk_ids_sha256"),
            "n_vectors": index_meta.get("n_vectors"),
            "token_limit": index_meta.get("token_limit"),
            "max_chunk_tokens": index_meta.get("max_chunk_tokens"),
            "built_at_utc": index_meta.get("created_at_utc"),
            "index_meta_sha256": index_meta_sha,
        },
        "generation": gen,
    }


@app.post(
    "/v1/answer",
    summary="Answer a clinical question",
    description=(
        "Calls the existing generation pipeline (retrieve → threshold gate → "
        "safety gate → generate → validate) and returns the full GenerationResult. "
        "No fake or fallback answers are produced — if the pipeline refuses, the "
        "refusal reason is included in the response."
    ),
    tags=["rag"],
)
def answer(req: AnswerRequest) -> dict[str, Any]:
    retriever = _require_retriever()

    try:
        result = answer_question(
            query=req.question,
            retriever=retriever,
            top_k=req.top_k,
            threshold=req.threshold,
        )
    except MissingAPIKeyError as exc:
        # The variable NAME is safe to state and is what an operator needs; the
        # exception text is logged rather than returned, on the same rule as
        # every other upstream failure below.
        log.error("LLM provider API key not configured: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "The language model provider is not configured for this deployment, "
                "so no answer can be generated."
            ),
        ) from exc
    except AnswerParseError as exc:
        # AnswerParseError subclasses ValueError, so it MUST be caught before
        # the ValueError branch below. It means the model returned something
        # that is not a JSON answer object (truncated, or prose) -- an upstream
        # failure, not a bad request. No answer is synthesised: the caller is
        # told generation failed.
        log.error("Model returned an unparseable answer: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=(
                "The language model did not return an answer in the required format, "
                "so nothing was produced. No answer was fabricated in its place."
            ),
        ) from exc
    except ProviderError as exc:
        # Rate limit, timeout, refused connection, empty completion. Upstream,
        # so 502 rather than 500 -- and again, never a fabricated answer.
        #
        # The exception text names the vendor, the model, the HTTP status and the
        # upstream body, which for a rate limit carries the account organisation
        # id and billing URLs. That is operator diagnostics, not caller-facing
        # content: it is logged here and replaced with SAFE_PROVIDER_MESSAGE in
        # the response.
        log.error("LLM provider call failed: %s", exc)
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=SAFE_PROVIDER_MESSAGE,
        ) from exc
    except ValueError as exc:
        # pipeline.answer_question raises ValueError for an empty/invalid query,
        # and the retriever for one over the length limit.
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(exc)) from exc
    except Exception as exc:  # noqa: BLE001
        # Qdrant connection error, network timeout, etc. Same rule: the detail is
        # logged, the caller is told what happened without the internals.
        log.exception("Unhandled error while answering a question")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The question could not be answered because of an internal error.",
        ) from exc

    payload = result.to_dict()

    # Structured stage timings. Durations, gate name and provider only: no
    # question text, no prompt, no retrieved passage, no credential. This is the
    # observability that was missing when a request could hang for four minutes
    # with nothing to say where the time went.
    timings = payload.get("timings_ms") or {}
    completion = (payload.get("generation") or {}).get("completion") or {}
    log.info(
        "answer stages_ms=%s total_ms=%s provider=%s refused=%s gate=%s citations=%d",
        {k: v for k, v in timings.items() if k != "total"},
        timings.get("total"),
        completion.get("provider"),
        payload.get("refused"),
        (payload.get("refusal") or {}).get("gate"),
        len((payload.get("answer") or {}).get("citations") or []),
    )
    return payload


@app.get(
    "/v1/corpus",
    summary="The guideline corpus behind the index",
    description=(
        "The authoritative documents the index was built from, read from "
        "data/processed/document_metadata.json, plus the number of indexed "
        "chunks each one contributes (counted in Qdrant, not assumed)."
    ),
    tags=["meta"],
)
def get_corpus() -> dict[str, Any]:
    docs, docs_sha = _frozen_or_503("document_metadata")

    # Per-document chunk counts come from the live collection, so the page shows
    # what is actually indexed rather than what a build report once said.
    counts: dict[str, int] = {}
    counts_source = "unavailable"
    if _retriever is not None:
        try:
            offset = None
            while True:
                points, offset = _retriever.client.scroll(
                    collection_name=_retriever.settings.collection,
                    limit=512,
                    with_payload=["document_id"],
                    with_vectors=False,
                    offset=offset,
                )
                for point in points:
                    doc_id = (point.payload or {}).get("document_id")
                    if doc_id:
                        counts[str(doc_id)] = counts.get(str(doc_id), 0) + 1
                if offset is None:
                    break
            counts_source = "qdrant"
        except Exception as exc:  # noqa: BLE001 - counts are additive, not essential
            log.warning("Could not count chunks per document: %s", exc)
            counts = {}

    documents = []
    for doc in docs if isinstance(docs, list) else []:
        entry = dict(doc)
        # source_path is a repo-relative path; the file itself is not served.
        entry.pop("source_path", None)
        entry["indexed_chunks"] = counts.get(str(doc.get("document_id")))
        documents.append(entry)

    return {
        "documents": documents,
        "n_documents": len(documents),
        "total_indexed_chunks": sum(counts.values()) if counts else None,
        "chunk_counts_source": counts_source,
        "provenance": {
            "file": "data/processed/document_metadata.json",
            "sha256": docs_sha,
        },
    }


@app.get(
    "/v1/evaluation",
    summary="The frozen retrieval evaluation",
    description=(
        "Serves eval/final_evaluation_results.json and "
        "eval/final_evaluation_summary.json verbatim, with the SHA-256 of the "
        "bytes read. Nothing is recomputed here — these are the published "
        "numbers, not a live rerun, and this endpoint has no way to produce "
        "any other value."
    ),
    tags=["meta"],
)
def get_evaluation() -> dict[str, Any]:
    results, results_sha = _frozen_or_503("evaluation_results")
    summary, summary_sha = _frozen_or_503("evaluation_summary")

    try:
        integrity, integrity_sha = _read_frozen("integrity_report")
    except Exception:  # noqa: BLE001 - the integrity report is optional
        integrity, integrity_sha = None, None

    return {
        "frozen": True,
        "shipped_config": "V1_atomic_pagesafe",
        "metrics": results.get("metrics", {}),
        "embedding_model": results.get("embedding_model"),
        "embedding_revision": results.get("embedding_revision"),
        "retrieval": results.get("retrieval"),
        "eval_depth": results.get("eval_depth"),
        "gold_sha256": results.get("gold_sha256"),
        "datasets_are_separate": results.get("datasets_are_separate"),
        "chunk_profiles": results.get("chunk_profiles", {}),
        "evidence_statistics": summary.get("evidence_statistics"),
        "final_interpretation": summary.get("final_interpretation"),
        "limitations": summary.get("limitations", []),
        "heldout_selection_rule": summary.get("heldout_selection_rule"),
        "integrity": (
            {
                "all_checks_passed": integrity.get("all_checks_passed"),
                "summary": integrity.get("summary"),
                "checks": integrity.get("checks", []),
            }
            if isinstance(integrity, dict)
            else None
        ),
        "provenance": {
            "final_evaluation_results.json": results_sha,
            "final_evaluation_summary.json": summary_sha,
            "integrity_report.json": integrity_sha,
        },
    }


@app.get(
    "/v1/chunks/{chunk_id}",
    summary="Retrieve chunk by ID",
    description=(
        "Fetches the full payload of a known chunk from Qdrant by its chunk_id "
        "(e.g. 'ESVS_2024__p26-26__c0093'). Used for audit and citation review."
    ),
    tags=["rag"],
)
def get_chunk(chunk_id: str) -> dict[str, Any]:
    retriever = _require_retriever()

    try:
        chunks = retriever.get_by_chunk_ids([chunk_id])
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Qdrant unavailable: {exc}",
        ) from exc

    if not chunks or chunk_id not in chunks:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Chunk '{chunk_id}' not found in the collection.",
        )

    return chunks[chunk_id]
